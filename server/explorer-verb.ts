import { execFile } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);

/** Same key name as a hand-made "OpenWithPaseo" verb, so registering replaces it */
const VERB_KEYS = [
  // Right-clicking a folder
  "HKCU\\Software\\Classes\\Directory\\shell\\OpenWithPaseo",
  // Right-clicking blank space inside a folder
  "HKCU\\Software\\Classes\\Directory\\Background\\shell\\OpenWithPaseo",
];

export interface ExplorerVerbOptions {
  launcherPath: string;
  requestDirectory: string;
  /** The desktop app, started when no Paseo window is open; null when the daemon is not the app's */
  paseoExecutable: string | null;
}

/** A PowerShell single-quoted literal */
function psLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

/**
 * Queues the folder for the plugin, then brings Paseo forward (or starts it). Explorer's click
 * gives this process the right to set the foreground window; the app itself cannot take it.
 */
export function launcherScript({ requestDirectory, paseoExecutable }: Omit<ExplorerVerbOptions, "launcherPath">): string {
  return `# Generated by the Paseo "Open with Paseo" plugin each time it loads; edits are overwritten.
param([Parameter(Mandatory = $true)][string]$Directory)
$ErrorActionPreference = 'Stop'
$requestDirectory = ${psLiteral(requestDirectory)}
$paseoExecutable = ${psLiteral(paseoExecutable ?? "")}

# The verb passes "%V\\." so a drive root's trailing backslash cannot escape the closing quote
$fullPath = [System.IO.Path]::GetFullPath($Directory)
if (-not [System.IO.Directory]::Exists($fullPath)) { exit 1 }

[void][System.IO.Directory]::CreateDirectory($requestDirectory)
$now = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
$name = '{0:D13}-{1}' -f $now, [guid]::NewGuid().ToString('N')
$json = ConvertTo-Json -Compress @{ path = $fullPath; requestedAt = $now }
$temporary = Join-Path $requestDirectory "$name.tmp"
[System.IO.File]::WriteAllText($temporary, $json, (New-Object System.Text.UTF8Encoding $false))
Move-Item -LiteralPath $temporary -Destination (Join-Path $requestDirectory "$name.json")

$window = Get-Process -Name Paseo -ErrorAction SilentlyContinue |
  Where-Object { $_.MainWindowHandle -ne [IntPtr]::Zero } |
  Select-Object -First 1
if ($window) {
  Add-Type -Namespace OpenWithPaseo -Name Win32 -MemberDefinition @'
[DllImport("user32.dll")] public static extern bool IsIconic(IntPtr hWnd);
[DllImport("user32.dll")] public static extern bool ShowWindowAsync(IntPtr hWnd, int nCmdShow);
[DllImport("user32.dll")] public static extern bool SetForegroundWindow(IntPtr hWnd);
'@
  # SW_RESTORE
  if ([OpenWithPaseo.Win32]::IsIconic($window.MainWindowHandle)) { [void][OpenWithPaseo.Win32]::ShowWindowAsync($window.MainWindowHandle, 9) }
  [void][OpenWithPaseo.Win32]::SetForegroundWindow($window.MainWindowHandle)
} elseif ($paseoExecutable) {
  Start-Process -FilePath $paseoExecutable
}
`;
}

/** conhost --headless runs PowerShell without flashing a console window */
export function verbCommand(launcherPath: string, systemRoot: string): string {
  const system32 = path.win32.join(systemRoot, "System32");
  const conhost = path.win32.join(system32, "conhost.exe");
  const powershell = path.win32.join(system32, "WindowsPowerShell", "v1.0", "powershell.exe");
  return `"${conhost}" --headless "${powershell}" -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${launcherPath}" "%V\\."`;
}

async function reg(args: string[]): Promise<void> {
  await execFileAsync("reg.exe", args, { windowsHide: true });
}

/** Writes the launcher and points both per-user Explorer verbs at it; idempotent */
export async function registerExplorerVerb(options: ExplorerVerbOptions): Promise<void> {
  await mkdir(path.dirname(options.launcherPath), { recursive: true });
  // Windows PowerShell reads a BOM-less script as the ANSI code page, mangling non-ASCII paths
  await writeFile(options.launcherPath, `\uFEFF${launcherScript(options)}`, "utf8");
  const command = verbCommand(options.launcherPath, process.env.SystemRoot ?? "C:\\Windows");
  for (const key of VERB_KEYS) {
    await reg(["add", key, "/v", "MUIVerb", "/d", "Open with Paseo", "/f"]);
    if (options.paseoExecutable) await reg(["add", key, "/v", "Icon", "/d", `"${options.paseoExecutable}",0`, "/f"]);
    await reg(["add", `${key}\\command`, "/ve", "/d", command, "/f"]);
  }
}

/** Deletes both per-user Explorer verbs; a verb that is already gone is fine */
export async function unregisterExplorerVerb(): Promise<void> {
  for (const key of VERB_KEYS) {
    try {
      await reg(["delete", key, "/f"]);
    } catch {
      // reg.exe exits 1 when the key does not exist
    }
  }
}
